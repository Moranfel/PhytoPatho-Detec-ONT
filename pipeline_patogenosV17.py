            content += (f'<p>Candidate reads: <strong>{decision["candidates"]:,}</strong> · '
                        f'Unique accepted reads in this group: <strong>{decision["unique_supported_reads"]:,}</strong></p>')
            best = decision["best_metrics"]
            if best:
                lines += [f"Top-ranked reference: {decision['best_reference']}",
                          f"Accepted reads: {best['reads']}; ≥95%: {best['reads95']}",
                          f"Mean identity: {best['mean_identity']:.2f}%; coverage: {best['coverage']:.4f}%; depth: {best['depth']:.4f}X"]
