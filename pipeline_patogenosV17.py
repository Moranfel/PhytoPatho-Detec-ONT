                content += '<details><summary>Compare all references</summary><div class="table-wrap"><table>'
                content += '<thead><tr><th>Reference</th><th>Reads</th><th>≥95%</th><th>Mean identity</th><th>Coverage</th><th>Depth</th></tr></thead><tbody>'
                for ref, data in sorted(sorted(decision["references"].items()), key=rank_key, reverse=True):
                    writer.writerow({"group": decision["group"], "reference": ref,
                                     "selected": ref == decision["best_reference"], **data})
                    content += (f'<tr><td>{e(ref)}</td><td class="numeric">{data["reads"]}</td>'
                                f'<td class="numeric">{data["reads95"]}</td><td class="numeric">{data["mean_identity"]:.2f}%</td>'
                                f'<td class="numeric">{data["coverage"]:.4f}%</td><td class="numeric">{data["depth"]:.4f}X</td></tr>')
